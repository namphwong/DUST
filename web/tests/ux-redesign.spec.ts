test('pasted CSV runs real pipeline: total distribution, selected time window, scores and export',async ({page})=>{
  const requests: string[] = [];
  page.on('request',r=>{if(r.method()!=='GET') requests.push(r.url());});
  await page.goto('/');
  await page.getByRole('tab',{name:'Dán dữ liệu'}).click();
  const csv = await readFile('../artifacts/phase6/fixtures/two-segments.csv','utf-8');
  await page.getByLabel('Dán CSV gồm header và các dòng dữ liệu').fill(csv);
  await page.getByRole('button',{name:'Sử dụng dữ liệu đã dán'}).click();
  await expect(page.getByTestId('source-file')).toContainText('du-lieu-da-dan.csv');
  await page.getByRole('checkbox',{name:'Gia tốc có bao gồm trọng lực'}).check();
  await page.getByRole('button',{name:'Kiểm tra resample'}).click();
  await expect(page.getByTestId('preparation-report')).toContainText('3 cửa sổ');
  await page.getByRole('checkbox',{name:/Tôi đã kiểm tra/}).check();
  await page.getByRole('button',{name:'Suy luận CSV'}).click();
  await expect(page.getByTestId('prediction')).toBeVisible({timeout:90000});
  await expect(page.getByRole('heading',{name:'Kết quả phân tích'})).toBeFocused();
  expect((await page.locator('.distribution-labels b').allTextContents()).reduce((sum,v)=>sum+Number(v),0)).toBe(3);
  await expect(page.getByTestId('selected-window')).toContainText('0.00–2.54 s');
  const golden = JSON.parse(await readFile('../artifacts/phase6/python-reference.json','utf-8')).cases.find((c:any)=>c.name==='two-segments');
  await page.getByTestId('prediction').locator('tbody button').last().click();
  await expect(page.getByTestId('selected-window')).toContainText('CHI TIẾT CỬA SỔ #2');
  await expect(page.getByTestId('selected-window')).toContainText('Đoạn 1 · 5.00–7.54 s');
  for(let c=0;c<6;c++) expect(Number((await page.locator('.score-row b').nth(c).textContent())!.replace('%',''))).toBeCloseTo(golden.windows[2].scores[c]*100,0);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Tải CSV kết quả ↓'}).click();
  const download = await downloadPromise;
  const output = await readFile((await download.path())!,'utf-8');
  expect(output.trim().split('\n')).toHaveLength(4);
  expect(output).toContain('1,2,5000,7540,');
  await page.setViewportSize({width:1366,height:768});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../artifacts/ui-redesign/desktop-output.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../artifacts/ui-redesign/mobile-output.png',fullPage:true});
  expect(requests).toEqual([]);
  await page.getByLabel('Đơn vị nguồn',{exact:true}).selectOption('ms2');
  await expect(page.getByTestId('prediction')).toHaveCount(0);
  await expect(page.getByTestId('output-empty')).toBeVisible();
  await writeFile('../artifacts/ui-redesign/verification.json',JSON.stringify({status:'passed',verifiedAt:new Date().toISOString(),inputModes:['file','drag-drop','paste'],realInference:true,selectedWindowMetadataAndScoresMatchGolden:true,distributionIsWindowCountNotDuration:true,allResultsExported:true,noNetworkWrites:true,unitChangeClearsOutput:true,desktopNoHorizontalOverflow:true,mobileNoHorizontalOverflow:true,userAgent:await page.evaluate(()=>navigator.userAgent)},null,2));
});

test('drag drop uses same validator; downloadable example is valid, synthetic and replaceable',async ({page})=>{
  await page.goto('/');
  const promised = page.waitForEvent('download');
  await page.getByRole('button',{name:'Tải CSV ví dụ',exact:true}).first().click();
  const example = await promised;
  const csv = await readFile((await example.path())!,'utf-8');
  expect(csv.trim().split('\n')).toHaveLength(129);
  const drag = await page.evaluateHandle((text)=>{
    const transfer = new DataTransfer(); transfer.items.add(new File([text],'keo-tha.csv',{type:'text/csv'}));return transfer;
  },csv);
  await page.locator('.upload-zone').dispatchEvent('drop',{dataTransfer:drag});
  await expect(page.getByTestId('source-file')).toContainText('keo-tha.csv');
  await expect(page.locator('.data-stats')).toContainText('128');
  await page.getByRole('checkbox',{name:'Gia tốc có bao gồm trọng lực'}).check();
  await page.getByRole('button',{name:'Kiểm tra resample'}).click();
  await expect(page.getByTestId('preparation-report')).toContainText('1 cửa sổ');
  await page.getByLabel('Chọn file CSV',{exact:true}).setInputFiles(resolve('../examples/phase0/invalid-number.csv'));
  await expect(page.getByRole('alert')).toContainText('INVALID_NUMBER');
  await expect(page.getByTestId('prediction')).toHaveCount(0);
  await drag.dispose();
});
